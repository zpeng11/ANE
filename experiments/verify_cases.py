#!/usr/bin/env python3
"""Verify that the committed opcases/ fixtures are exactly reproducible.

The check is offline: it runs mil_gen.py into a temporary directory (never the
committed tree), compares every generated byte, and validates the 76-case
_index.txt manifest.  `make verify-cases` and the offline test suite both use
this module.
"""
import argparse
import hashlib
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent
CASES = ROOT / "opcases"
EXPECTED_INDEX = 76


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def generate(output):
    """Run the canonical generator into output (an isolated directory)."""
    result = subprocess.run(
        [sys.executable, str(ROOT / "mil_gen.py"), "--output", str(output)],
        cwd=ROOT, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(
            "mil_gen.py failed\nstdout:\n" + result.stdout + "\nstderr:\n" + result.stderr)
    return result.stdout.strip()


def compare_trees(expected, generated):
    expected_files = {p.relative_to(expected) for p in expected.rglob("*") if p.is_file()}
    generated_files = {p.relative_to(generated) for p in generated.rglob("*") if p.is_file()}
    differing = []
    for name in sorted(expected_files & generated_files):
        if sha256(expected / name) != sha256(generated / name):
            differing.append(str(name))
    return {
        "expected_files": len(expected_files),
        "generated_files": len(generated_files),
        "missing": sorted(str(name) for name in expected_files - generated_files),
        "extra": sorted(str(name) for name in generated_files - expected_files),
        "differing": differing,
    }


def index_report():
    index = CASES / "_index.txt"
    names = [line.strip() for line in index.read_text().splitlines() if line.strip()]
    unique = sorted(set(names))
    return {
        "expected_index": EXPECTED_INDEX,
        "declared": len(names),
        "unique": len(unique),
        "duplicates": sorted({name for name in names if names.count(name) > 1}),
        "missing_mil": [name for name in unique
                        if not (CASES / (name + ".mil")).is_file()],
        "missing_meta": [name for name in unique
                         if not (CASES / (name + ".meta")).is_file()],
        "unindexed_mil": sorted({p.stem for p in CASES.glob("*.mil")} - set(unique)),
        "sorted": names == unique,
    }


def verify():
    manifest = index_report()
    with tempfile.TemporaryDirectory(prefix="ane-verify-cases-") as temp:
        first = Path(temp) / "first" / "opcases"
        second = Path(temp) / "second" / "opcases"
        first.parent.mkdir(parents=True)
        second.parent.mkdir(parents=True)
        first_log = generate(first)
        second_log = generate(second)
        against_commit = compare_trees(CASES, first)
        first_vs_second = compare_trees(first, second)

    ok = (
        manifest["declared"] == EXPECTED_INDEX
        and manifest["unique"] == EXPECTED_INDEX
        and not manifest["duplicates"]
        and not manifest["missing_mil"]
        and not manifest["missing_meta"]
        and not manifest["unindexed_mil"]
        and manifest["sorted"]
        and against_commit["expected_files"] == against_commit["generated_files"]
        and not against_commit["missing"]
        and not against_commit["extra"]
        and not against_commit["differing"]
        and not first_vs_second["differing"]
        and not first_vs_second["missing"]
        and not first_vs_second["extra"]
    )
    return ok, {
        "manifest": manifest,
        "against_commit": against_commit,
        "run1_vs_run2": first_vs_second,
        "generator": {"first": first_log, "second": second_log},
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quiet", action="store_true",
                        help="Only print the final status line")
    args = parser.parse_args()
    ok, report = verify()
    if not args.quiet:
        manifest = report["manifest"]
        commit = report["against_commit"]
        repeat = report["run1_vs_run2"]
        print(f"index: declared={manifest['declared']} unique={manifest['unique']} "
              f"expected={manifest['expected_index']}")
        print(f"files: committed={commit['expected_files']} "
              f"generated={commit['generated_files']}")
        print(f"against committed: missing={len(commit['missing'])} "
              f"extra={len(commit['extra'])} differing={len(commit['differing'])}")
        print(f"run1 vs run2: missing={len(repeat['missing'])} "
              f"extra={len(repeat['extra'])} differing={len(repeat['differing'])}")
        for label, entries in (
                ("missing vs commit", commit["missing"]),
                ("extra vs commit", commit["extra"]),
                ("differing vs commit", commit["differing"]),
                ("duplicate index", manifest["duplicates"]),
                ("missing .mil", manifest["missing_mil"]),
                ("missing .meta", manifest["missing_meta"]),
                ("unindexed .mil", manifest["unindexed_mil"])):
            for entry in entries:
                print(f"  {label}: {entry}")
    print("verify-cases: " + ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
